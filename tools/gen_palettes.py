#!/usr/bin/env python3
"""Generates the colour-palette theme overlays from tools/palettes.json.

Every colour the UI uses is a theme attribute ``pal_<colour>`` (res/values/attrs_palette.xml),
whose default is the matching @color resource (the "Classic" palette). Each other palette is
a style ``Palette.<Name>`` that overrides those attributes; MainActivity applies the chosen
one on top of AppTheme. Light values go to res/values/palettes.xml and dark values to
res/values-night/palettes.xml, so the night qualifier picks the right set.

Run after editing tools/palettes.json:  python3 tools/gen_palettes.py
"""
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
PALETTES = json.loads((ROOT / "tools/palettes.json").read_text(encoding="utf-8"))
HEADER = "<!-- Generated by tools/gen_palettes.py from tools/palettes.json. Do not edit. -->\n"


def style_name(palette_id):
    return "Palette." + "".join(part.capitalize() for part in palette_id.split("_"))


def rgba(value):
    value = value.strip()
    if value.startswith("#"):
        hex_part = value[1:]
        alpha = 1.0
        if len(hex_part) == 8:
            alpha = int(hex_part[:2], 16) / 255
            hex_part = hex_part[2:]
        return tuple(int(hex_part[i:i + 2], 16) for i in (0, 2, 4)) + (alpha,)
    m = re.match(r"rgba\(([\d.]+),([\d.]+),([\d.]+),([\d.]+)\)", value.replace(" ", ""))
    return (float(m[1]), float(m[2]), float(m[3]), float(m[4]))


def argb(value, alpha=None):
    r, g, b, a = rgba(value)
    a = a if alpha is None else alpha
    return f"#{round(a * 255):02X}{round(r):02X}{round(g):02X}{round(b):02X}"


def blend(top, bottom, amount):
    """`top` laid over `bottom` with opacity `amount`, as opaque #RRGGBB."""
    r, g, b, _ = rgba(top)
    R, G, B, _ = rgba(bottom)
    mix = lambda x, y: round(x * amount + y * (1 - amount))
    return f"#{mix(r, R):02X}{mix(g, G):02X}{mix(b, B):02X}"


def colours(t, dark):
    """Maps a palette's tokens onto the app's colour names."""
    return {
        "bg": t["bg"],
        "surface": t["surface"],
        "surface_alt": t["alt"],
        "border": t["border"],
        "floating_border": t["border"],
        "divider": t["divider"],
        "text_primary": t["text"],
        "text_secondary": t["text2"],
        "blue": t["primary"],
        "primary_fill": t["fill"],
        "primary_pressed": t["fill"],
        "primary_disabled": blend(t["fill"], t["surface"], 0.45),
        "hero_start": t["hero"][0],
        "hero_center": t["hero"][1],
        "hero_end": t["hero"][2],
        "hero_start_glass": argb(t["hero"][0], 0.6),
        "hero_center_glass": argb(t["hero"][1], 0.6),
        "hero_end_glass": argb(t["hero"][2], 0.6),
        "hero_pill": argb(t["pill"]),
        "info_bg": t["info"],
        "green": t["g"][1],
        "yellow": t["y"][1],
        "red": t["red"],
        "status_value_green_bg": argb(t["g"][0]),
        "status_value_yellow_bg": argb(t["y"][0]),
        "status_value_red_bg": argb(t["r"][0]),
        "status_value_neutral_bg": argb(t["n"][0]),
        "status_value_blue_bg": argb(t["primary"], 0.2 if dark else 0.14),
        "badge_text_green": t["g"][1],
        "badge_text_yellow": t["y"][1],
        "badge_text_red": t["r"][1],
        "badge_text_neutral": t["n"][1],
        "glass_header": argb(t["bg"], 0.72),
        "glass_surface": argb(t["surface"], 0.70 if dark else 0.75),
        "switch_track_off": t["off"],
        "switch_track_disabled": blend(t["off"], t["surface"], 0.5),
        "segment_selected": blend("#FFFFFF", t["alt"], 0.08) if dark else t["surface"],
    }


def defined_colours():
    root = ET.parse(RES / "values/colors.xml").getroot()
    return [c.attrib["name"] for c in root if c.tag == "color"]


def write(path, body):
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + HEADER + body, encoding="utf-8")


def main():
    names = defined_colours()
    attrs = "<resources>\n" + "".join(
        f'    <attr name="pal_{n}" format="color" />\n' for n in names) + "</resources>\n"
    write(RES / "values/attrs_palette.xml", attrs)

    for folder, mode in (("values", "light"), ("values-night", "dark")):
        out = ["<resources>\n"]
        for palette in PALETTES:
            out.append(f'    <style name="{style_name(palette["id"])}" parent="">\n')
            if palette["id"] != "classic":  # Classic = the @color defaults in AppTheme.
                for name, value in colours(palette[mode], mode == "dark").items():
                    if name not in names:
                        raise SystemExit(f"unknown colour {name}")
                    out.append(f'        <item name="pal_{name}">{value}</item>\n')
            out.append("    </style>\n")
        out.append("</resources>\n")
        write(RES / folder / "palettes.xml", "".join(out))
    print(f"{len(PALETTES)} palettes, {len(names)} colour attributes")


if __name__ == "__main__":
    main()
